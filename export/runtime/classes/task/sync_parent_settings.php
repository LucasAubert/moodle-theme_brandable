namespace theme_brandablert\task;

/**
 * Copies the parent settings changed without event (set_config() called directly).
 *
 * @package    theme_brandable
 * @copyright  2026 Lucas Aubert
 * @license    https://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class sync_parent_settings extends \core\task\scheduled_task {
    /**
     * Returns the task name.
     *
     * @return string
     */
    public function get_name(): string {
        return get_string('task:syncparentsettings', 'theme_brandablert');
    }

    /**
     * Runs the task.
     */
    public function execute(): void {
        if (\theme_brandablert\brandable\settings_mirror::sync_all()) {
            theme_reset_all_caches();
        }
    }
}
